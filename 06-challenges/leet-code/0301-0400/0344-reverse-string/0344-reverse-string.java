// https://leetcode.com/problems/reverse-string/

// Solution: Two Pointers — O(n) time, O(1) space
class Solution {
    public void reverseString(char[] s) {
        int left = 0, right = s.length - 1;
        while (left < right) {
            char tmp = s[left];
            s[left] = s[right];
            s[right] = tmp;
            left++;
            right--;
        }
    }
}
