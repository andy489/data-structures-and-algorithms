// https://leetcode.com/problems/remove-element/

// Solution: Two Pointers — O(n) time, O(1) space
class Solution {
    public int removeElement(int[] nums, int val) {
        int k = 0;
        for (int i = 0; i < nums.length; i++) {
            if (nums[i] != val) {
                nums[k++] = nums[i];
            }
        }
        return k;
    }
}
